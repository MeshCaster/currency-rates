from collections.abc import Collection
from datetime import date, datetime
from typing import Protocol, Sequence
from uuid import UUID

from core.pagination import Page
from domain.alerts import Alert, AlertRule, PriceSample
from domain.enums import AlertSeverity, AlertStatus, IntervalKind
from domain.models import ProviderCapability, Rate, SyncConfig
from domain.users import Subscription, User


class RateProvider(Protocol):

    name: str

    async def get_rate(self, base: str, quote: str) -> Rate: ...


class HistoricalRateProvider(Protocol):
    name: str

    async def get_rate(self, base: str, quote: str, on: date) -> Rate: ...


class RateHistoryProvider(Protocol):
    name: str
    chunk_days: int

    async def get_history(self, base: str, quote: str, start: date, end: date,
                          interval: IntervalKind) -> list[Rate]: ...


class RateRepository(Protocol):
    async def add_many(self, rates: Sequence[Rate]) -> int: ...
    async def upsert_many(self, rates: Sequence[Rate]) -> int: ...
    async def latest(self, base: str, quote: str, source: str | None = None) -> Rate | None: ...
    async def history(self, base: str, quote: str, page: int = 1, size: int = 50,
                      official_only: bool = True) -> Page[Rate]: ...
    async def list_pairs(self, include_cross: bool = False) -> list[tuple[str, str]]: ...


class SyncConfigurationRepository(Protocol):
    async def get(self, id: UUID) -> SyncConfig | None: ...
    async def add(self, entity: SyncConfig) -> None: ...
    async def exists_for(self, provider_id: UUID, base: str, quote: str,
                         interval: IntervalKind) -> bool: ...
    async def search(self, *, provider: str | None = None, is_active: bool | None = None,
                     page: int = 1, size: int = 50) -> Page[SyncConfig]: ...
    async def list_due(self, as_of: date) -> list[SyncConfig]: ...
    async def advance(self, config: SyncConfig, synced_until: date) -> SyncConfig: ...
    async def record_failure(self, id: UUID, error: str) -> None: ...


class ProviderCatalog(Protocol):
    async def get_by_key(self, key: str) -> ProviderCapability | None: ...
    async def supports_currency(self, provider_id: UUID, currency: str) -> bool: ...


class AlertRuleRepository(Protocol):
    async def get(self, id: UUID) -> AlertRule | None: ...
    async def add(self, entity: AlertRule) -> None: ...
    async def update(self, entity: AlertRule) -> None: ...
    async def delete(self, id: UUID) -> None: ...
    async def list_active(self) -> list[AlertRule]: ...
    async def search(self, *, sync_configuration_id: UUID | None = None,
                     is_active: bool | None = None, page: int = 1,
                     size: int = 50) -> Page[AlertRule]: ...


class AlertRepository(Protocol):
    async def get(self, id: UUID) -> Alert | None: ...
    async def add(self, entity: Alert) -> None: ...
    async def update(self, entity: Alert) -> None: ...
    async def unresolved_for(self, rule_ids: Collection[UUID]) -> dict[UUID, Alert]: ...
    async def search(self, *, status: AlertStatus | None = None,
                     severity: AlertSeverity | None = None, rule_id: UUID | None = None,
                     page: int = 1, size: int = 50) -> Page[Alert]: ...


class PriceSampleRepository(Protocol):
    async def add_many(self, samples: Sequence[PriceSample]) -> int: ...
    async def latest(self, sync_configuration_id: UUID,
                     at_or_before: datetime) -> PriceSample | None: ...
    async def prune(self, older_than: datetime) -> int: ...


class UserRepository(Protocol):
    async def get(self, id: UUID) -> User | None: ...
    async def get_by_email(self, email: str) -> User | None: ...
    async def add(self, entity: User) -> None: ...
    async def update(self, entity: User) -> None: ...


class SubscriptionRepository(Protocol):
    async def get(self, id: UUID) -> Subscription | None: ...
    async def add(self, entity: Subscription) -> None: ...
    async def update(self, entity: Subscription) -> None: ...
    async def delete(self, id: UUID) -> None: ...
    async def list_for_user(self, user_id: UUID) -> list[Subscription]: ...
    async def exists_for(self, user_id: UUID, sync_configuration_id: UUID) -> bool: ...
    async def list_deliverable(self) -> list[tuple[Subscription, str]]: ...
    async def mark_sent(self, ids: Collection[UUID], on: date) -> None: ...


class EmailSender(Protocol):
    async def send(self, to: str, subject: str, text: str, html: str | None = None) -> None: ...
